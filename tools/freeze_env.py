"""Seal the exact measured environment. G0-prime, against the risk that "it worked on my machine"
becomes a load-bearing statement.

WHY A LOCK AND NOT JUST requirements.txt. `requirements.txt` names six packages and no versions, and
the venv actually holds 29 -- including five (fastapi, starlette, uvicorn, pydantic, anyio) that
nothing in the repository imports. Interpreter is a component of every journal seal in this program,
so an unpinned environment is a seal with a hole in it. This writes the full frozen set as a tracked
artifact, generated rather than pasted, so a reader can re-run it and diff.

It does NOT pin requirements.txt. That is a separate decision with consequences for every install,
and it is registered as an open item, not made silently here.

Run:  .venv/Scripts/python.exe tools/freeze_env.py
"""
from __future__ import annotations

import argparse
import hashlib
import platform
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
DEFAULT_OUT = HERE / "experiments" / "G0-prime" / "results" / "requirements.lock.txt"


def git(*a) -> str:
    r = subprocess.run(["git", *a], cwd=str(HERE), capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args()

    r = subprocess.run([sys.executable, "-m", "pip", "freeze", "--disable-pip-version-check"],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[-1500:])
        return 1
    pkgs = sorted(x for x in r.stdout.splitlines() if x.strip())

    body = "\n".join(pkgs) + "\n"
    header = (
        "# Exact measured environment for G0-prime and MP-E9 -- GENERATED by tools/freeze_env.py,\n"
        "# not hand-maintained. Regenerate and diff rather than editing.\n"
        f"#   interpreter      : {sys.version.split()[0]} ({platform.python_implementation()})\n"
        f"#   prefix           : {sys.prefix}\n"
        f"#   base_prefix      : {sys.base_prefix}\n"
        f"#   in_venv          : {sys.prefix != sys.base_prefix}\n"
        f"#   platform         : {platform.platform()}\n"
        f"#   git_head         : {git('rev-parse', 'HEAD')}\n"
        f"#   packages         : {len(pkgs)}\n"
        f"#   frozen_at_utc    : {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}\n"
        "#\n"
        "# requirements.txt names six packages with no versions. This list is the set the numbers\n"
        "# were actually measured in. fastapi/starlette/uvicorn/pydantic/anyio are installed and\n"
        "# imported by nothing in the repository; they are recorded because the environment and the\n"
        "# requirements file are not the same set, and a seal cannot be built on the difference.\n"
        "# pypdf is the only package added by this session; it is imported by the tracked\n"
        "# experiments/MP-E9/plan_extract/extract_pdf.py and by no organ or harness.\n"
    )
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + body, encoding="utf-8", newline="\n")

    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    print(f"[freeze] {len(pkgs)} packages -> {out.relative_to(HERE).as_posix()}")
    print(f"[freeze] package-list sha256: {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
