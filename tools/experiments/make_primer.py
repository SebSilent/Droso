"""Build the grounded primer: the language environment Droso is raised in.

This is exposure material, not his output -- the equivalent of the simplified,
repetitive, here-and-now speech a caregiver actually uses with a child who has
heard almost nothing. Every sentence is about something in HIS world: the phase
of the day, care, his body, the people in the room, the house, files and tasks,
and the act of speaking itself. Nothing refers to a world he cannot touch.

Volume matters for order. A chain organ learns transitions, and transitions need
repetition in varied frames, so the corpus is generated by combining a small
grounded vocabulary across a fixed set of sentence frames rather than typed once
by hand. Run it, and the book is rewritten deterministically.

    python tools/make_primer.py
"""
from __future__ import annotations

import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "books" / "grounded_primer.txt"

SUBJECTS = ["i", "you", "we", "droso", "parent"]
OBJECTS = ["you", "me", "this", "that", "the word", "the file", "the light",
           "the food", "home", "the world"]
VERBS_SEE = ["see", "hear", "know", "want", "hold", "read", "say"]
VERBS_DO = ["open", "close", "finish", "start", "learn", "remember", "forget"]
STATES = ["here", "warm", "safe", "quiet", "bright", "dark", "new", "good",
          "calm", "open", "closed", "done"]
FEELINGS = ["tired", "calm", "happy", "lonely", "curious", "hungry", "awake"]
DAY = ["the day is bright", "the day is long", "it is day now",
       "the sun is up", "a new day starts", "the light is warm",
       "day is for learning", "the world is bright"]
NIGHT = ["the night is quiet", "the night is dark", "it is night now",
         "night is coming", "the light is going", "night is for rest",
         "the world is quiet", "the dark is calm"]
CARE = ["i am feeding you", "this is food", "you are eating",
        "the food is warm", "you are full now", "i am petting you",
        "that is a pet", "you did well", "that was good",
        "i am proud of you", "you are safe", "you are cared for"]
NAME = ["my name is parent", "your name is droso", "you are droso",
        "i am your parent", "names are words", "say my name",
        "you have a name", "i have a name", "droso is my name"]
SPEECH = ["say it again", "say one word", "say two words", "say it slowly",
          "i am listening", "listen to me", "i hear you", "you are speaking",
          "we are speaking", "speaking is good", "listening is good",
          "a word is a sound", "a sound has meaning", "words are ours",
          "hold this word", "give me the word", "take the word",
          "the word is yours", "i will teach you", "you learn every day"]
BODY = ["you are tired now", "you need rest", "rest a moment",
        "sleep now droso", "wake up droso", "you are growing",
        "your brain changed", "something is new", "something changed",
        "you remember this", "do not forget", "i remember you",
        "we remember this"]
WORLD = ["this is home", "home is warm", "home is safe", "look at this",
         "come here now", "stay here now", "the world is big",
         "this is the world", "we are together", "you are not alone"]
WORK = ["this is a file", "the file is open", "the file is closed",
        "read the file", "write the word", "that was a task",
        "the work is done", "you did the work", "i am working",
        "we are working"]

QA_PAIRS = [
    # Question and answer on consecutive lines. The question mark is the only
    # annotation, and it is the last one: which role a question word asks about
    # is written down nowhere. It is recovered by comparing each question with
    # the answer that follows it -- whichever role's filler is missing from the
    # question is the role being asked about, and whatever word the question adds
    # is the interrogative that asks for it.
    ("who feeds droso?", "parent feeds droso"),
    ("who pets droso?", "parent pets droso"),
    ("who warms food?", "parent warms food"),
    ("who holds light?", "parent holds light"),
    ("who opens file?", "parent opens file"),
    ("who sees light?", "droso sees light"),
    ("who hears world?", "droso hears world"),
    ("who learns word?", "droso learns word"),
    ("droso sees what?", "droso sees light"),
    ("droso wants what?", "droso wants food"),
    ("droso hears what?", "droso hears sound"),
    ("droso learns what?", "droso learns word"),
    ("droso finds what?", "droso finds file"),
    ("parent opens what?", "parent opens file"),
    ("where is droso?", "droso is home"),
    ("where is parent?", "parent is here"),
    ("where is light?", "light is here"),
    ("where is food?", "food is here"),
    ("where is file?", "file is here"),
    ("how is droso?", "droso is calm"),
    ("how is parent?", "parent is warm"),
    ("how is day?", "day is bright"),
    ("how is night?", "night is quiet"),
    ("how is food?", "food is warm"),
]

FRAMES = [
    # Roles are CONSISTENT, because a caregiver's speech is. "parent" is always
    # the one who cares, gives and opens; "droso" is always the one who perceives,
    # wants and learns; "i" is always the parent speaking and "you" is always
    # droso. Random combinations of subject and verb were the reason role recovery
    # sat at the base rate: with five subjects uniformly distributed over every
    # verb, the correct answer is only 20% likely a priori and no mechanism can
    # beat that. Structure in the input is what makes roles learnable.
    "parent {pv} droso",
    "parent {pv} the {n}",
    "parent is {st}",
    "droso {dv} the {n}",
    "droso {dv} {o}",
    "droso is {f}",
    "i {pv} you",
    "i {pv} the {n}",
    "i am {f}",
    "you {dv} the {n}",
    "you are {f}",
    "you are {st}",
    "we {wv} the {n}",
    "we are {st}",
    "is droso {f}",
    "is the {n} {st}",
    "do not {dv} the {n}",
    "look at the {n}",
    "say {o}",
    "this is the {n}",
    "the {n} is {st}",
    "parent and droso are {st}",
    "i see you",
    "you see me",
]

# verbs partitioned by who does them, which is the structure he has to discover
PARENT_VERBS = ["feeds", "pets", "holds", "opens", "closes", "gives",
                "washes", "warms", "helps", "carries"]
DROSO_VERBS = ["sees", "hears", "wants", "learns", "finds", "watches",
               "smells", "touches", "follows", "remembers"]
SHARED_VERBS = ["say", "read", "learn", "hear", "see", "hold", "open",
                "close", "find", "want"]
NOUNS = ["word", "file", "light", "food", "home", "day", "night", "world",
         "name", "sound", "work", "task", "hand", "book", "water"]
OBJECTS = ["you", "me", "this", "that", "home", "it"]


def build(seed: int = 7, per_frame: int = 26) -> list[str]:
    rng = random.Random(seed)
    fixed: list[str] = []
    # the grounded sentences a caregiver repeats verbatim
    for group in (DAY, NIGHT, CARE, NAME, SPEECH, BODY, WORLD, WORK):
        fixed.extend(group)
    # Question/answer pairs are NEVER de-duplicated. An answer line can belong to
    # two different questions ("droso sees light" answers both "who sees light?"
    # and "droso sees what?"), and removing the second copy left the question
    # followed by another question -- which is how "what" never learned that it
    # gets answered with `light` and `word`, and how `sees` and `learns` were
    # mis-learned as question words at all. Adjacency IS the supervision here, so
    # nothing may reorder or thin it.
    qa: list[str] = []
    for q, a in QA_PAIRS:
        qa.append(q)
        qa.append(a)
    generated: list[str] = []
    for frame in FRAMES:
        for _ in range(per_frame):
            sent = frame.format(
                pv=rng.choice(PARENT_VERBS), dv=rng.choice(DROSO_VERBS),
                wv=rng.choice(SHARED_VERBS), n=rng.choice(NOUNS),
                o=rng.choice(OBJECTS), st=rng.choice(STATES),
                f=rng.choice(FEELINGS))
            sent = " ".join(sent.split())
            if 2 <= len(sent.split()) <= 8:
                generated.append(sent)
    # Only the generated frames are thinned, and only against each other.
    seen, frames = set(), []
    for s in generated:
        if s not in seen:
            seen.add(s)
            frames.append(s)
    out = []
    for s in fixed + qa + frames:
        if s not in out or s in qa:
            out.append(s)
    return out


def main() -> int:
    lines = build()
    OUT.parent.mkdir(exist_ok=True, parents=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    words = sum(len(l.split()) for l in lines)
    vocab = sorted({w for l in lines for w in l.split()})
    print(f"wrote {OUT}")
    print(f"  {len(lines)} sentences, {words} words, {len(vocab)} distinct")
    print(f"  mean length {words / max(1, len(lines)):.1f} words")
    print("  sample:", " | ".join(lines[:4]))
    print("  sample:", " | ".join(lines[-4:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
